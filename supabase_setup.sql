-- 1. Create the inventory table
CREATE TABLE IF NOT EXISTS inventory (
  product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_name TEXT NOT NULL,
  category_id BIGINT DEFAULT 1,
  category_name TEXT DEFAULT 'General',
  buying_price NUMERIC(10, 2) DEFAULT 0.00,
  selling_price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  quantity_in_stock INTEGER NOT NULL DEFAULT 0,
  reorder_level INTEGER NOT NULL DEFAULT 5,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE inventory ENABLE ROW LEVEL SECURITY;

-- 3. Create RLS Policies
-- Allow anyone to view products
CREATE POLICY "Allow public read access" 
  ON inventory FOR SELECT 
  USING (true);

-- Allow backend service role to insert, update, and delete
CREATE POLICY "Allow full access for authenticated/service role" 
  ON inventory FOR ALL 
  USING (true)
  WITH CHECK (true);

