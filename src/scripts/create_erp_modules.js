const schemaSql = `
  -- Administrative Module (Users & System Settings)
  CREATE TABLE IF NOT EXISTS users_accounts (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    role TEXT NOT NULL DEFAULT 'technician', -- 'owner', 'admin', 'service_manager', 'technician', 'finance_manager', 'dispatch_manager', 'driver', 'inventory_manager'
    status TEXT NOT NULL DEFAULT 'active',
    phone TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
  );

  -- Customer Module (Customers & Warranties)
  CREATE TABLE IF NOT EXISTS customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    phone TEXT NOT NULL,
    email TEXT,
    location TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
  );

  CREATE TABLE IF NOT EXISTS warranties (
    warranty_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT REFERENCES customers(customer_id) ON DELETE CASCADE,
    product_name TEXT NOT NULL,
    serial_no TEXT,
    start_date DATE DEFAULT CURRENT_DATE,
    expiry_date DATE,
    status TEXT DEFAULT 'active', -- 'active', 'expired', 'claimed'
    created_at TIMESTAMPTZ DEFAULT NOW()
  );

  -- Service Manager & Technician Module (Installation & Repair Jobs)
  CREATE TABLE IF NOT EXISTS service_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT NOT NULL,
    phone TEXT NOT NULL,
    location TEXT NOT NULL,
    service_type TEXT NOT NULL, -- 'Solar Installation', 'Wiring & Rewiring', 'Fault Repair', 'Appliance Repair', 'Panel Board Setup'
    description TEXT,
    assigned_technician_id BIGINT REFERENCES users_accounts(user_id) ON DELETE SET NULL,
    technician_name TEXT,
    materials_used TEXT,
    status TEXT DEFAULT 'pending', -- 'pending', 'assigned', 'in_progress', 'completed', 'cancelled'
    scheduled_date DATE,
    created_at TIMESTAMPTZ DEFAULT NOW()
  );

  -- Finance Manager Module (Sales, Expenses & Payments)
  CREATE TABLE IF NOT EXISTS finance_records (
    record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT NOT NULL, -- 'sale', 'expense', 'refund'
    category TEXT NOT NULL, -- 'Shop Sale', 'Installation Fee', 'Inventory Purchase', 'Transport', 'Utilities', 'Salaries'
    description TEXT NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    payment_method TEXT DEFAULT 'M-Pesa', -- 'M-Pesa', 'Cash', 'Bank Transfer'
    reference_no TEXT,
    status TEXT DEFAULT 'confirmed', -- 'confirmed', 'pending', 'cancelled'
    created_at TIMESTAMPTZ DEFAULT NOW()
  );

  -- Dispatch & Driver Module
  CREATE TABLE IF NOT EXISTS dispatches (
    dispatch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no TEXT NOT NULL,
    customer_name TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    delivery_address TEXT NOT NULL,
    driver_id BIGINT REFERENCES users_accounts(user_id) ON DELETE SET NULL,
    driver_name TEXT,
    scheduled_date DATE DEFAULT CURRENT_DATE,
    status TEXT DEFAULT 'pending_dispatch', -- 'pending_dispatch', 'out_for_delivery', 'delivered', 'failed'
    driver_notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
  );

  -- Inventory Stock Movements (Stock-in / Stock-out)
  CREATE TABLE IF NOT EXISTS stock_movements (
    movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES inventory(product_id) ON DELETE CASCADE,
    product_name TEXT NOT NULL,
    type TEXT NOT NULL, -- 'STOCK_IN', 'STOCK_OUT', 'DAMAGE_WRITE_OFF'
    quantity INTEGER NOT NULL,
    reason TEXT,
    recorded_by TEXT DEFAULT 'Inventory Manager',
    created_at TIMESTAMPTZ DEFAULT NOW()
  );

  -- Enable RLS and full access policies on all new tables
  ALTER TABLE users_accounts ENABLE ROW LEVEL SECURITY;
  ALTER TABLE customers ENABLE ROW LEVEL SECURITY;
  ALTER TABLE warranties ENABLE ROW LEVEL SECURITY;
  ALTER TABLE service_requests ENABLE ROW LEVEL SECURITY;
  ALTER TABLE finance_records ENABLE ROW LEVEL SECURITY;
  ALTER TABLE dispatches ENABLE ROW LEVEL SECURITY;
  ALTER TABLE stock_movements ENABLE ROW LEVEL SECURITY;

  DO $$
  DECLARE
    tbl text;
  BEGIN
    FOR tbl IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
      EXECUTE format('DROP POLICY IF EXISTS "Allow full access for service role" ON %I;', tbl);
      EXECUTE format('CREATE POLICY "Allow full access for service role" ON %I FOR ALL USING (true) WITH CHECK (true);', tbl);
    END LOOP;
  END $$;
`;

