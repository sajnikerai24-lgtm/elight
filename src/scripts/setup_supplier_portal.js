async function ensureStorageBucket() {
  const { data: buckets, error } = await supabase.storage.listBuckets();
  if (error) {
    console.warn('⚠️ Could not list storage buckets:', error.message);
    return;
  }
  const exists = buckets.some(b => b.name === 'supplier-documents');
  if (!exists) {
    const { error: createErr } = await supabase.storage.createBucket('supplier-documents', {
      public: false,
      fileSizeLimit: 5 * 1024 * 1024
    });
    if (createErr) {
      console.warn('⚠️ Could not create bucket supplier-documents:', createErr.message);
    } else {
      console.log('✅ Created private storage bucket: supplier-documents');
    }
  } else {
    console.log('✅ Storage bucket supplier-documents already exists.');
  }
}

async function provisionSupplierAuthAccount(supplierRow, initialPassword) {
  const email = String(supplierRow.email || '').trim().toLowerCase();
  if (!email) return null;

  const { data: listRes } = await supabase.auth.admin.listUsers({ perPage: 1000 });
  const existingUser = (listRes?.users || []).find(
    u => String(u.email || '').toLowerCase() === email
  );

  let authUserId = existingUser ? existingUser.id : null;
  if (!authUserId) {
    const { data: created, error } = await supabase.auth.admin.createUser({
      email,
      password: initialPassword,
      email_confirm: true,
      app_metadata: { role: 'supplier', supplier_id: Number(supplierRow.supplier_id) },
      user_metadata: {
        full_name: supplierRow.contact_person || supplierRow.supplier_name,
        company_name: supplierRow.supplier_name
      }
    });
    if (error) throw new Error(`Failed creating auth for ${email}: ${error.message}`);
    authUserId = created.user.id;
    console.log(`✅ Created Supabase Auth account for ${supplierRow.supplier_name} (${email})`);
  } else {
    await supabase.auth.admin.updateUserById(authUserId, {
      password: initialPassword,
      email_confirm: true,
      app_metadata: { role: 'supplier', supplier_id: Number(supplierRow.supplier_id) },
      user_metadata: {
        full_name: supplierRow.contact_person || supplierRow.supplier_name,
        company_name: supplierRow.supplier_name
      }
    });
    console.log(`✅ Linked existing Supabase Auth account for ${supplierRow.supplier_name} (${email})`);
  }

  await pg.query(
    `UPDATE public.suppliers
     SET auth_user_id = $1,
         status = 'active',
         account_created_at = COALESCE(account_created_at, NOW()),
         updated_at = NOW()
     WHERE supplier_id = $2`,
    [authUserId, supplierRow.supplier_id]
  );

  return authUserId;
}

