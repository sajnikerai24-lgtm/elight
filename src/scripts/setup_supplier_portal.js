async function main() {
  try {
    await pg.connect();
    console.log('Connected to Supabase PostgreSQL...');
    await pg.query(schemaSql);
    console.log('✅ Supplier Portal schema & strict RLS policies applied.');

    await ensureStorageBucket();

    const { rows: suppliers } = await pg.query('SELECT * FROM public.suppliers ORDER BY supplier_id ASC');
    const demoPasswords = {
      1: 'PhilipsSup#2026',
      2: 'SchneiderSup#2026',
      3: 'MetsecSup#2026'
    };
    for (const s of suppliers) {
      if (s.email && !s.auth_user_id) {
        const pwd = demoPasswords[Number(s.supplier_id)] || 'Supplier#2026!';
        await provisionSupplierAuthAccount(s, pwd);
      } else if (s.email && s.auth_user_id && demoPasswords[Number(s.supplier_id)]) {
        await provisionSupplierAuthAccount(s, demoPasswords[Number(s.supplier_id)]);
      }
    }

    await seedSupplierWorkflowData();
    console.log('🎉 Multi-Supplier Portal database setup complete!');
  } catch (err) {
    console.error('❌ Setup failed:', err);
    process.exit(1);
  } finally {
    await pg.end();
  }
}

main();

